"""
Central configuration for RoboticsDistanceTracker.

Edit the values below to match YOUR physical setup. Nothing in this file is
a stand-in for real data -- CAMERA_IDS, the field size, and the detection
thresholds all need to reflect your actual cameras/field/lighting. Run
list_cameras.py to find real indices and tune_colors.py to find real HSV
thresholds; don't hand-guess numbers here.
"""
import os

# ---------------------------------------------------------------------------
# Camera setup
# ---------------------------------------------------------------------------
# Windows/DirectShow indices for your three webcams, in whatever order you
# want them displayed/fused. Run `python list_cameras.py` to see a live
# preview of each index and figure out which physical camera is which.
CAMERA_IDS = [1]

FRAME_WIDTH = 1280
FRAME_HEIGHT = 720
FRAME_FPS = 30

# ---------------------------------------------------------------------------
# Field geometry (inches) -- standard FTC field is 12ft x 12ft made of
# 24in x 24in foam tiles (6x6 grid). Change these if your field differs.
# ---------------------------------------------------------------------------
FIELD_WIDTH_IN = 144.0
FIELD_HEIGHT_IN = 144.0
TILE_SIZE_IN = 24.0

# ---------------------------------------------------------------------------
# File paths (generated by the calibration/tuning tools -- do not hand-edit
# the JSON, re-run the tools instead so the numbers stay real)
# ---------------------------------------------------------------------------
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CALIBRATION_FILE = os.path.join(BASE_DIR, "calibration.json")
HSV_CONFIG_FILE = os.path.join(BASE_DIR, "hsv_config.json")
INTRINSICS_FILE = os.path.join(BASE_DIR, "intrinsics.json")

# ---------------------------------------------------------------------------
# Lens (intrinsic) calibration -- corrects lens distortion before the
# homography is applied. See calibrate_intrinsics.py.
# ---------------------------------------------------------------------------
# Inner-corner count of your printed checkerboard, as (columns, rows) --
# NOT the number of squares. A checkerboard with 10x7 squares has a (9, 6)
# grid of internal corners (where 4 squares meet). Count carefully.
CHECKERBOARD_INNER_CORNERS = (9, 6)

# Real edge length of one checkerboard square, in inches. MEASURE YOUR
# ACTUAL PRINTOUT WITH A RULER before setting this -- printer scaling is
# not always exact, and this number directly scales calibration accuracy.
CHECKERBOARD_SQUARE_SIZE_IN = 1.0

# Minimum number of good checkerboard captures (spread across the frame,
# at varied distances/angles/tilts) required before calibrate_intrinsics.py
# lets you finish a camera. More captures = more accurate distortion model.
MIN_INTRINSIC_CAPTURES = 15

# ---------------------------------------------------------------------------
# Detection tuning
# ---------------------------------------------------------------------------
# Minimum contour area (in pixels, at FRAME_WIDTH x FRAME_HEIGHT) for a
# blob to be considered a real detection rather than noise.
MIN_BALL_AREA_PX = 150
MIN_ROBOT_AREA_PX = 500

# How close to a perfect circle (1.0) a ball contour must be. Game balls
# are not perfectly spherical and get squashed by perspective at oblique
# camera angles, so don't set this too near 1.0 -- if real balls go
# undetected, this is the first value to loosen (0.65-0.75 is reasonable).
BALL_MIN_CIRCULARITY = 0.85

# Real-world radius of the game ball, in inches. Used to correct for
# parallax: a raised object's ground-contact point is not the same as its
# pixel centroid unless the camera is directly overhead.
BALL_RADIUS_IN = 1.5

# ---------------------------------------------------------------------------
# Object classes
# ---------------------------------------------------------------------------
# Every label here can be tuned with:  python tune_colors.py --label <name>
# and is stored under that name in hsv_config.json.
#
#   robot        - a distinct color patch on the robot (bumper/flag), not the
#                  whole chassis. Required; this is what gives robot position.
#   robot_front  - optional heading marker at the FRONT of the robot
#   robot_back   - optional heading marker at the BACK of the robot
#
# Heading needs BOTH robot_front and robot_back tuned. If either is missing,
# position still works and heading is simply reported as unavailable.
#
# Marker color budget: pick hues that can't collide with the game elements
# below (yellow/red/blue are taken). Green and magenta/purple are the open
# slots -- see the hue table in the README.
ROBOT_LABEL = "robot"
ROBOT_FRONT_LABEL = "robot_front"
ROBOT_BACK_LABEL = "robot_back"

# Ball-like classes, with their real-world diameters in inches. Size is a
# lighting-independent discriminator: color thresholds drift between venues
# but physical diameter doesn't, so detections are checked against both.
BALL_CLASSES = {
    "pollen": 2.8,
    "nectar_red": 3.6,
    "nectar_blue": 3.6,
}

# How far a measured diameter may differ from the expected diameter above
# and still be accepted, as a fraction. 0.35 = accept 65%-135% of expected.
# Balls are imperfect spheres and the homography has its own error, so this
# needs real slack -- tighten it only if different classes are being mixed up.
BALL_SIZE_TOLERANCE = 0.35

COLOR_LABELS = [ROBOT_LABEL, ROBOT_FRONT_LABEL, ROBOT_BACK_LABEL] + list(BALL_CLASSES)

# ---------------------------------------------------------------------------
# Declustering (splitting balls that touch each other into separate detections)
# ---------------------------------------------------------------------------
# Touching balls merge into one contour. When a blob's area is at least this
# multiple of one ball's expected area, it's treated as a cluster and split
# with a distance-transform watershed.
ENABLE_DECLUSTER = True
CLUSTER_AREA_FACTOR = 1.6

# Distance-transform threshold for finding cluster seeds, as a fraction of
# one ball's expected pixel radius. Lower = more aggressive splitting (risks
# splitting a single ball); higher = more conservative (risks merging).
CLUSTER_SEED_FRACTION = 0.55

# Safety cap on how many balls one blob may be split into.
CLUSTER_MAX_SPLIT = 12

# ---------------------------------------------------------------------------
# Heading (robot pose) smoothing
# ---------------------------------------------------------------------------
# Heading is smoothed by averaging the heading unit vector, which avoids the
# wraparound bug you get from averaging raw angles across 0/360 degrees.
# 0 = no smoothing, 0.9 = very heavy smoothing (and laggy).
HEADING_SMOOTHING = 0.6

# ---------------------------------------------------------------------------
# Multi-camera fusion
# ---------------------------------------------------------------------------
# When the same object is seen by more than one camera, detections are
# averaged. Detections whose pixel position is within this many pixels of
# the frame edge are down-weighted (lens distortion + oblique angle error
# are worst near the edges of the frame).
EDGE_MARGIN_PX = 60
EDGE_WEIGHT = 0.35  # weight applied to near-edge detections vs 1.0 for central ones

# Max distance (inches) between two cameras' estimates of "the same object"
# before they're treated as separate objects instead of being fused. Only
# matters when there's more than one ball on the field.
FUSION_MATCH_RADIUS_IN = 8.0

# ---------------------------------------------------------------------------
# Temporal smoothing (Kalman filter on the fused robot/ball positions)
# ---------------------------------------------------------------------------
# Set False to see raw, unsmoothed fused positions (useful when comparing
# behavior or debugging detection itself).
ENABLE_SMOOTHING = True

# How much to trust the constant-velocity motion model vs. new
# measurements. Higher = reacts faster to real movement, less jitter
# reduction. Lower = smoother but lags behind fast movement more.
SMOOTHING_PROCESS_NOISE = 5.0

# Assumed noise in each fused measurement. Higher = trust raw detections
# less (smoother, laggier). Lower = trust them more (less lag, less
# jitter reduction).
SMOOTHING_MEASUREMENT_NOISE = 1.0

# How many consecutive frames a track may go undetected (brief occlusion,
# a dropped camera frame) while coasting on its predicted position before
# it's dropped entirely. Also used as the matching radius (inches) for
# associating a new frame's fused ball positions back to existing tracks.
SMOOTHING_MAX_MISSED_FRAMES = 10
